import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PWPATH);
const m = JSON.parse(readFileSync('src/data/map.json'));
const S = m.size, SQ3 = Math.sqrt(3);
const col = { P: '#cfe0a0', F: '#7fae6a', M: '#9b8a6a', R: '#7fb7d8' };
let svg = '';
const pts = (x, y) => [...Array(6)].map((_, k) => { const a = Math.PI / 180 * (60 * k - 30); return `${(x + S * Math.cos(a)).toFixed(1)},${(y + S * Math.sin(a)).toFixed(1)}`; }).join(' ');
let minx = 1e9, miny = 1e9, maxx = -1e9, maxy = -1e9;
const mode = process.argv[2] || 'terrain';
const hue = i => `hsl(${(i * 137.5) % 360},55%,65%)`;
m.hexes.forEach(h => { const x = S * SQ3 * (h.q + h.r / 2), y = S * 1.5 * h.r; minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y);
  const fill = mode === 'terrain' ? col[h.t] : mode === 'prov' ? hue(h.p) : hue(h.d);
  svg += `<polygon points="${pts(x, y)}" fill="${fill}" stroke="#555" stroke-width="0.5"/>`;
  if (h.c !== undefined) svg += `<rect x="${x - 4}" y="${y - 4}" width="8" height="8" fill="#000"/><text x="${x}" y="${y - 6}" font-size="8" text-anchor="middle">${m.castles[h.c].name}</text>`;
});
const W = maxx - minx + 40, H = maxy - miny + 40;
const html = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="${minx - 20} ${miny - 20} ${W} ${H}"><rect x="${minx-20}" y="${miny-20}" width="${W}" height="${H}" fill="#24456b"/>${svg}</svg>`;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(() => chromium.launch());
const p = await b.newPage({ viewport: { width: Math.ceil(W), height: Math.ceil(H) } });
await p.setContent(html); await p.screenshot({ path: process.argv[3] }); await b.close();
